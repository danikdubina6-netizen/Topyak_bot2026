def get_random_phrase():
    category = random.choice(list(PHRASES.keys()))
    return random.choice(PHRASES[category])

@bot.message_handler(func=lambda message: True)
def handle_message(message):
    if message.from_user.id == bot.get_me().id:
        return

    chat_type = message.chat.type
    text = message.text.lower() if message.text else ""

    if chat_type == 'private':
        try:
            time.sleep(0.2)
            bot.send_message(message.chat.id, get_random_phrase())
        except Exception as e:
            print(f"Ошибка ЛС: {e}")
        return

    is_mentioned = f"@{BOT_USERNAME}" in text
    is_reply_to_bot = message.reply_to_message and message.reply_to_message.from_user.id == bot.get_me().id

    if is_mentioned or is_reply_to_bot:
        try:
            time.sleep(0.2)
            bot.reply_to(message, get_random_phrase())
            print("[DEBUG] Бот ответил на прямое упоминание/реплай в группе!")
        except Exception as e:
            print(f"Ошибка ответа по упоминанию: {e}")
        return

    group_id = message.chat.id
    group_counters[group_id] += 1
    print(f"[DEBUG] Группа {group_id} | Счётчик сообщений: {group_counters[group_id]}/15")

    if group_counters[group_id] >= 15:
        group_counters[group_id] = 0
        try:
            time.sleep(0.3)
            bot.reply_to(message, get_random_phrase())
            print("[DEBUG] Сработал счетчик 15 сообщений в группе!")
        except Exception as e:
            print(f"Ошибка в группе: {e}")

