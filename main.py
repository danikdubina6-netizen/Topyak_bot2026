@bot.message_handler(func=lambda message: True)
def handle_all_messages(message):
  global group_message_counter

  chat_type = message.chat.type
  text = message.text or ''
  text_lower = text.lower()

  # 1. АБСОЛЮТНЫЙ ПРИОРИТЕТ: Фича "Скажи..."
  if text_lower.startswith('скажи '):
    said_text = text[6:].strip()
    if said_text:
      bot.reply_to(message, said_text)
      return

  # 2. Если это личные сообщения — отвечаем сразу
  if chat_type == 'private':
    response_text = random.choice(RANDOM_PHRASES)
    bot.reply_to(message, response_text)
    return

  # 3. Если это группы/супергруппы
  if chat_type in ['group', 'supergroup']:
    is_reply_to_bot = (
        message.reply_to_message
        and message.reply_to_message.from_user.id == bot.get_me().id
    )
    is_mentioned = False

    bot_username = bot.get_me().username
    if bot_username and f'@{bot_username.lower()}' in text_lower:
      is_mentioned = True

    # Если бота упомянули или ответили на его сообщение (или другого бота)
    if is_reply_to_bot or is_mentioned:
      response_text = random.choice(RANDOM_PHRASES)
      bot.reply_to(message, response_text)
      return

    # Обычное фоновое сообщение в группе — крутим счетчик до 15
    group_message_counter += 1
    if group_message_counter >= 15:
      group_message_counter = 0

      action_type = random.choice(['reply', 'reaction'])
      if action_type == 'reply':
        response_text = random.choice(RANDOM_PHRASES)
        bot.reply_to(message, response_text)
      else:
        try:
          bot.set_message_reaction(
              message.chat.id,
              message.message_id,
              [telebot.types.ReactionTypeEmoji('😋')],
          )
        except Exception:
          response_text = random.choice(RANDOM_PHRASES)
          bot.reply_to(message, response_text)


