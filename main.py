def get_smart_reply(text):
    text_lower = text.lower()
    selected_category = None

    # Ищем категорию по ключевым словам
    for cat, words in KEYWORDS.items():
        if any(word in text_lower for word in words):
            selected_category = cat
            break

    # Если ключевое слово не найдено — берем рандомную категорию со всеми темами
    if not selected_category:
        selected_category = random.choice(list(SMART_DATABASE.keys()))

    return random.choice(SMART_DATABASE[selected_category])


@bot.message_handler(func=lambda message: True)
def handle_message(message):
    text = message.text

    # Фильтр спама
    spam_words = [
        "пробив",
        "госномер",
        "поиск человека",
        "бесплатно",
        "vpn",
        "впн",
    ]
    if any(word in text.lower() for word in spam_words):
        try:
            bot.delete_message(message.chat.id, message.id)
        except Exception:
            pass
        return

    reply_text = get_smart_reply(text)
    sent_msg = bot.reply_to(message, reply_text)

    try:
        reaction = random.choice(AVAILABLE_REACTIONS)
        bot.set_message_reaction(
            message.chat.id,
            sent_msg.message_id,
            [telebot.types.ReactionTypeEmoji(reaction)],
        )
    except Exception:
        pass


